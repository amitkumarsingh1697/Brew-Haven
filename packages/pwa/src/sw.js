import { strategyFor } from "./strategy.js";

/**
 * Builds the service worker script. `version` names the caches so each deploy starts clean;
 * `precache` is the app shell (index.html plus its entry script and styles) saved on install so
 * the app opens with no connection.
 */
/**
 * @param {{ version: string; precache: string[]; appName: string }} opts
 * @returns {string}
 */
export function serviceWorkerSource(opts) {
  return `/* ${opts.appName} service worker, build ${opts.version}. Generated by @brew-haven/pwa. */
const VERSION = ${JSON.stringify(opts.version)};
const SHELL = "shell-" + VERSION;
const ASSETS = "assets-" + VERSION;
const STATIC = "static-v1";
const PRECACHE = ${JSON.stringify(opts.precache)};
const MAX_ASSETS = 80;
const strategyFor = ${strategyFor.toString()};

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const shell = await caches.open(SHELL);
      await shell.addAll(PRECACHE.filter((p) => !p.startsWith("/assets/")));
      const assets = await caches.open(ASSETS);
      await assets.addAll(PRECACHE.filter((p) => p.startsWith("/assets/")));
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keep = new Set([SHELL, ASSETS, STATIC]);
      for (const key of await caches.keys()) if (!keep.has(key)) await caches.delete(key);
      await self.clients.claim();
    })(),
  );
});

async function trim(cache) {
  const keys = await cache.keys();
  for (const k of keys.slice(0, Math.max(0, keys.length - MAX_ASSETS))) await cache.delete(k);
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const kind = strategyFor(req.url, req.method, req.mode, self.location.origin);
  if (kind === "skip") return;

  if (kind === "page") {
    event.respondWith(
      (async () => {
        const shell = await caches.open(SHELL);
        try {
          const res = await fetch(req);
          if (res.ok) await shell.put("/index.html", res.clone());
          return res;
        } catch {
          return (await shell.match("/index.html")) || Response.error();
        }
      })(),
    );
    return;
  }

  if (kind === "asset") {
    event.respondWith(
      (async () => {
        const cache = await caches.open(ASSETS);
        const hit = await cache.match(req);
        if (hit) return hit;
        const res = await fetch(req);
        if (res.ok) {
          await cache.put(req, res.clone());
          void trim(cache);
        }
        return res;
      })(),
    );
    return;
  }

  // static: serve what we have, refresh in the background.
  event.respondWith(
    (async () => {
      const cache = await caches.open(STATIC);
      const hit = await cache.match(req);
      const fresh = fetch(req)
        .then((res) => {
          if (res.ok || res.type === "opaque") void cache.put(req, res.clone());
          return res;
        })
        .catch(() => hit || Response.error());
      if (hit) {
        event.waitUntil(fresh.then(() => undefined));
        return hit;
      }
      return fresh;
    })(),
  );
});
`;
}
